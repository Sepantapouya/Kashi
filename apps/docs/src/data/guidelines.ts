export interface Example {
  /** توضیح نمونه؛ کد لاتین داخل `بک‌تیک` */
  text: string;
  /** پیش‌نمایش ایستا با کلاس‌های k-* (اختیاری) */
  html?: string;
}
export interface Guideline {
  use: string[];
  /** [متن، پیوند جایگزین، عنوان پیوند] */
  avoid: [string, string?, string?][];
  pairs: { do: Example; dont: Example }[];
  /** نکته‌های متن همین کامپوننت */
  writing?: string[];
}

// ساخت پیش‌نمایش‌ها با همان HTML کامپوننت‌های کاشی
const btn = (label: string, variant = "secondary", size = "") => `<button type="button" class="k-btn k-btn--${variant}${size ? ` k-btn--${size}` : ""}">${label}</button>`;
const field = (label: string, value = "", o: { error?: string; hint?: string; placeholder?: string; ltr?: boolean; w?: string } = {}) =>
  `<div class="k-field" style="inline-size: ${o.w ?? "16rem"}"${o.error ? ' data-invalid=""' : ""}><div class="k-field__label-row"><label class="k-label">${label}</label></div>` +
  `<div class="k-input" data-size="md"${o.error ? ' data-state="invalid"' : ""}><input class="k-input__control" value="${value}"${o.placeholder ? ` placeholder="${o.placeholder}"` : ""}${o.ltr ? ' dir="ltr"' : ""}${o.error ? ' aria-invalid="true"' : ""}></div>` +
  (o.error || o.hint ? `<div class="k-field__hint-row"><div class="k-field__hints"><p class="k-hint${o.error ? " k-hint--error" : ""}">${o.error ?? o.hint}</p></div></div>` : "") + "</div>";
const badge = (label: string, tone = "neutral") => `<span class="k-badge${tone !== "neutral" ? ` k-badge--${tone}` : ""}">${label}</span>`;
const alert = (title: string, text: string, tone = "warning") =>
  `<div class="k-alert k-alert--${tone}" style="inline-size: 20rem"><div class="k-alert__content"><p class="k-alert__title">${title}</p><div class="k-alert__description">${text}</div></div></div>`;
const check = (label: string, checked = false, sw = false) =>
  `<label class="k-check"><input type="checkbox"${sw ? ' role="switch"' : ""} class="k-${sw ? "switch" : "checkbox"}"${checked ? " checked" : ""}><span class="k-check__text"><span class="k-check__label">${label}</span></span></label>`;
const stack = (...parts: string[]) => `<div style="display: grid; gap: 0.5rem; justify-items: start">${parts.join("")}</div>`;
const empty = (title: string, text?: string) => `<div class="k-empty" style="inline-size: 18rem"><p class="k-empty__title">${title}</p>${text ? `<p class="k-empty__description">${text}</p>` : ""}</div>`;

