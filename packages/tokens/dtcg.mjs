// خروجی توکن‌ها با قالب استاندارد W3C Design Tokens (DTCG 2025.10) برای Figma Variables، Style Dictionary و Tokens Studio.
//   dist/dtcg/kashi.tokens.json          مقادیر پایه (رنگ، فاصله، گوشه، فونت، حرکت، لایه، نقطهٔ شکست)
//   dist/dtcg/theme-dark.tokens.json     توکن‌های معنایی و سایه‌های تم تیره، با ارجاع به مقادیر پایه
//   dist/dtcg/theme-light.tokens.json    …روشن
//   dist/dtcg/theme-*-contrast.tokens.json  …با کنتراست بالا (کل تم، نه فقط تفاوت‌ها؛ هر حالت در فیگما کامل است)
// گوشه و اندازهٔ متن با ضریب ۱ حساب می‌شوند (knobs پیش‌فرض)؛ ضریب‌ها خودشان هم به‌صورت number در فایل پایه هستند.
import { mkdirSync, writeFileSync } from "node:fs";

const SCHEMA = "https://www.designtokens.org/schemas/2025.10/format.json";
const key = (k) => String(k).replace(".", "_");

// ---------- رنگ
const hexToRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const round = (n, d = 4) => Math.round(n * 10 ** d) / 10 ** d;
const toHex = (c) => "#" + c.map((v) => Math.round(v * 255).toString(16).padStart(2, "0")).join("");
const color = (rgb, alpha = 1) => ({
  colorSpace: "srgb",
  components: rgb.map((c) => round(c)),
  ...(alpha < 1 ? { alpha: round(alpha, 3) } : {}),
  hex: toHex(rgb),
});

/** مقدار رنگ CSS کاشی → مقدار DTCG یا ارجاع {…} */
function colorValue(v, t, ctx) {
  let m;
  v = v.trim();
  if (/^#[0-9a-f]{6}$/i.test(v)) return color(hexToRgb(v));
  if (/^#[0-9a-f]{8}$/i.test(v)) return color(hexToRgb(v.slice(0, 7)), parseInt(v.slice(7), 16) / 255);
  if (/^#0000$/.test(v)) return color([0, 0, 0], 0);
  if ((m = v.match(/^var\(--k-([a-z]+)-(\d+)\)$/)) && (m[1] === "brand" || t.palette[m[1]])) return `{color.${m[1]}.${m[2]}}`;
  if ((m = v.match(/^var\(--k-([a-z-]+)\)$/)) && ctx?.[m[1]] !== undefined) return `{${semanticPath(m[1]).join(".")}}`;
  if ((m = v.match(/^rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)$/))) return color([+m[1] / 255, +m[2] / 255, +m[3] / 255], +m[4]);
  if ((m = v.match(/^color-mix\(in srgb, var\(--k-([a-z]+)-(\d+)\) (\d+)%, transparent\)$/))) {
    const scale = m[1] === "brand" ? "firoozeh" : m[1];
    return color(hexToRgb(t.palette[scale][m[2]]), +m[3] / 100);
  }
  throw new Error(`dtcg: cannot convert color ${v}`);
}

// ---------- اندازه
function dimension(v) {
  let m;
  v = String(v).trim();
  if (v === "0") return { value: 0, unit: "px" };
  if ((m = v.match(/^(-?[\d.]+)(px|rem)$/))) return { value: +m[1], unit: m[2] };
  // calc(0.75rem * var(--k-radius-factor)) با ضریب پیش‌فرض ۱
  if ((m = v.match(/^calc\(([\d.]+)rem \* var\(--k-[a-z-]+\)\)$/))) return { value: +m[1], unit: "rem" };
  throw new Error(`dtcg: cannot convert dimension ${v}`);
}

/** «a, b(c, d), e» → ["a", "b(c, d)", "e"] */
function splitTop(s) {
  const out = [];
  let depth = 0, cur = "";
  for (const ch of s) {
    if (ch === "(") depth++;
    if (ch === ")") depth--;
    if (ch === "," && depth === 0) {
      out.push(cur.trim());
      cur = "";
    } else cur += ch;
  }
  if (cur.trim()) out.push(cur.trim());
  return out;
}

/** box-shadow کاشی → سایهٔ DTCG (یک لایه یا آرایه) */
function shadowValue(v, t, ctx) {
  const layers = splitTop(v).map((layer) => {
    const parts = [];
    let depth = 0, cur = "";
    for (const ch of layer) {
      if (ch === "(") depth++;
      if (ch === ")") depth--;
      if (ch === " " && depth === 0) {
        if (cur) parts.push(cur);
        cur = "";
      } else cur += ch;
    }
    if (cur) parts.push(cur);
    const inset = parts[0] === "inset" ? parts.shift() && true : false;
    const lengths = parts.filter((p) => /^-?[\d.]+(px|rem)?$/.test(p));
    const col = parts.find((p) => !/^-?[\d.]+(px|rem)?$/.test(p));
    const [x = "0", y = "0", blur = "0", spread = "0"] = lengths;
    return {
      color: colorValue(col, t, ctx),
      offsetX: dimension(x),
      offsetY: dimension(y),
      blur: dimension(blur),
      spread: dimension(spread),
      ...(inset ? { inset: true } : {}),
    };
  });
  return layers.length === 1 ? layers[0] : layers;
}

const fontFamily = (v) => splitTop(v).map((f) => f.replace(/^["']|["']$/g, ""));
const cubic = (v) => v.match(/cubic-bezier\(([^)]+)\)/)[1].split(",").map((n) => +n);

/** «bg-brand-hover» → ["bg", "brand-hover"]؛ «highlight» → ["highlight"] */
function semanticPath(name) {
  const i = name.indexOf("-");
  return i === -1 ? [name] : [name.slice(0, i), name.slice(i + 1)];
}

function set(obj, path, token) {
  let o = obj;
  for (const p of path.slice(0, -1)) o = o[p] ??= {};
  o[path.at(-1)] = token;
}

// ---------- مقادیر پایه
function primitives(t) {
  const out = { $schema: SCHEMA, $description: "Kashi design tokens (primitives). Generated by @kashi-ui/tokens." };
  out.color = {};
  for (const [scale, steps] of Object.entries(t.palette)) {
    out.color[scale] = { $type: "color" };
    for (const [step, hex] of Object.entries(steps)) out.color[scale][step] = { $value: color(hexToRgb(hex)) };
  }
  // brand نام مستعار فیروزه‌ای است؛ برای برند دیگر فقط این گروه را عوض کنید
  out.color.brand = { $type: "color", $description: "Brand alias (Firoozeh by default)." };
  for (const step of Object.keys(t.palette.firoozeh)) out.color.brand[step] = { $value: `{color.firoozeh.${step}}` };

  out.knob = { $type: "number" };
  for (const [k, v] of Object.entries(t.knobs)) out.knob[k] = { $value: +v };

  out.space = { $type: "dimension" };
  for (const [k, v] of Object.entries(t.space)) out.space[key(k)] = { $value: dimension(v) };

  out.radius = { $type: "dimension" };
  for (const [k, v] of Object.entries(t.radius)) {
    const m = v.match(/^var\(--k-radius-([a-z0-9]+)\)$/);
    out.radius[k] = { $value: m ? `{radius.${m[1]}}` : dimension(v) };
  }

  out.font = {
    family: { $type: "fontFamily" },
    size: { $type: "dimension" },
    weight: { $type: "fontWeight" },
    leading: { $type: "number" },
  };
  for (const [k, v] of Object.entries(t.font.family)) {
    const m = v.match(/^var\(--k-font-([a-z]+)\)$/);
    out.font.family[k] = { $value: m ? `{font.family.${m[1]}}` : fontFamily(v) };
  }
  for (const [k, v] of Object.entries(t.font.size)) out.font.size[k] = { $value: dimension(v) };
  for (const [k, v] of Object.entries(t.font.weight)) out.font.weight[k] = { $value: +v };
  for (const [k, v] of Object.entries(t.font.leading)) out.font.leading[k] = { $value: +v };

  // سایه‌ها در CSS هم پایه‌اند و هم در هر تم بازنویسی می‌شوند؛ در DTCG فقط در فایل تم‌اند تا دو فایل با هم برخورد نکنند

  out.duration = { $type: "duration" };
  for (const [k, v] of Object.entries(t.motion.duration)) out.duration[k] = { $value: { value: parseFloat(v), unit: "ms" } };
  out.easing = { $type: "cubicBezier" };
  for (const [k, v] of Object.entries(t.motion.easing)) out.easing[k] = { $value: cubic(v) };

  out.zIndex = { $type: "number" };
  for (const [k, v] of Object.entries(t.zIndex)) out.zIndex[k] = { $value: +v };
  out.breakpoint = { $type: "dimension", $description: "Min-width breakpoints (same values as Tailwind, plus xs)." };
  for (const [k, v] of Object.entries(t.breakpoint)) out.breakpoint[k] = { $value: dimension(v) };
  return out;
}

// ---------- توکن‌های معنایی یک تم
function theme(t, values, description) {
  // توضیح در $extensions، نه $description ریشه: ابزارهایی مثل Style Dictionary فایل‌ها را ادغام می‌کنند و توضیح ریشه برخورد می‌کند
  const out = { $schema: SCHEMA, $extensions: { "com.kashi-ui": { mode: description } } };
  for (const [name, v] of Object.entries(values)) {
    const path = semanticPath(name);
    const isShadow = /^(shadow|ring|highlight)/.test(name);
    const token = isShadow
      ? { $type: "shadow", $value: shadowValue(v, t, values) }
      : { $type: "color", $value: colorValue(v, t, values) };
    set(out, path, token);
  }
  return out;
}

export function writeDtcg(t, dir) {
  mkdirSync(dir, { recursive: true });
  const files = {
    "kashi.tokens.json": primitives(t),
    "theme-dark.tokens.json": theme(t, t.themes.dark, "Kashi semantic tokens, dark theme (default)."),
    "theme-light.tokens.json": theme(t, t.themes.light, "Kashi semantic tokens, light theme."),
    "theme-dark-contrast.tokens.json": theme(t, { ...t.themes.dark, ...t.contrastThemes.dark }, "Kashi semantic tokens, dark theme with high contrast (WCAG AAA text)."),
    "theme-light-contrast.tokens.json": theme(t, { ...t.themes.light, ...t.contrastThemes.light }, "Kashi semantic tokens, light theme with high contrast (WCAG AAA text)."),
  };
  for (const [name, data] of Object.entries(files)) writeFileSync(`${dir}/${name}`, JSON.stringify(data, null, 2) + "\n");
  return Object.keys(files);
}
